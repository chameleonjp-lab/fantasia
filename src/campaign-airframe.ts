// Support vertices copied from fixed Kaisen 3d751051 (see provenance manifest).
import type { Vec, CampaignPlayer } from './campaign-types';
import { addVec, copyVec, lerpVec, segmentSphereEntry, subtractVec, terrainHeight, sweepObstacles, TERRAIN_MAX_HEIGHT } from './campaign-terrain';
export type PlainQuaternion = CampaignPlayer['quaternion'];
export const AIRFRAME_CONTACT_RADIUS = 6.303;
export const AIRCRAFT_HIT_SPHERES = Object.freeze([
  { center: { x: 0, y: 0, z: -3.8 }, radius: 3 },
  { center: { x: 0, y: 0, z: 0 }, radius: 4.6 },
  { center: { x: 0, y: 0, z: 3.4 }, radius: 2.7 },
  { center: { x: 4, y: 0, z: .25 }, radius: 2.1 },
  { center: { x: -4, y: 0, z: .25 }, radius: 2.1 },
]);
export function rotateVec(v: Vec, q: PlainQuaternion): Vec {
  const x = v.x, y = v.y, z = v.z, qx = q.x, qy = q.y, qz = q.z, qw = q.w;
  const tx = 2 * (qy * z - qz * y), ty = 2 * (qz * x - qx * z), tz = 2 * (qx * y - qy * x);
  return { x: x + qw * tx + qy * tz - qz * ty, y: y + qw * ty + qz * tx - qx * tz, z: z + qw * tz + qx * ty - qy * tx };
}
function normalizeQuaternion(q: PlainQuaternion): PlainQuaternion {
  const norm = Math.hypot(q.x, q.y, q.z, q.w);
  if (norm < 1e-12 || !Number.isFinite(norm)) throw new RangeError('Invalid player quaternion');
  return { x: q.x / norm, y: q.y / norm, z: q.z / norm, w: q.w / norm };
}
function interpolateQuaternion(a: PlainQuaternion, b: PlainQuaternion, t: number): PlainQuaternion {
  let cosine = a.x * b.x + a.y * b.y + a.z * b.z + a.w * b.w;
  const sign = cosine < 0 ? -1 : 1; cosine = Math.abs(cosine);
  let left = 1 - t, right = t;
  if (cosine < .9995) { const angle = Math.acos(Math.min(1, cosine)), sine = Math.sin(angle); left = Math.sin((1 - t) * angle) / sine; right = Math.sin(t * angle) / sine; }
  return normalizeQuaternion({ x: a.x * left + b.x * right * sign, y: a.y * left + b.y * right * sign, z: a.z * left + b.z * right * sign, w: a.w * left + b.w * right * sign });
}
/** K's five collision spheres, swept relative to the projectile motion. */
export function sweptPlayerHit(from: Vec, to: Vec, player: CampaignPlayer, projectileRadius = 0): number | null {
  if (segmentSphereEntry(subtractVec(from, player.previous), subtractVec(to, player.position), 8 + projectileRadius) === null) return null;
  let first: number | null = null;
  for (const sphere of AIRCRAFT_HIT_SPHERES) {
    const previous = addVec(player.previous, rotateVec(sphere.center, player.previousQuaternion));
    const current = addVec(player.position, rotateVec(sphere.center, player.quaternion));
    const entry = segmentSphereEntry(subtractVec(from, previous), subtractVec(to, current), sphere.radius + projectileRadius);
    if (entry !== null && (first === null || entry < first)) first = entry;
  }
  return first;
}
/** Preserve K's actual support hull for ground contact, including rotation. */
export function aircraftTerrainContact(player: CampaignPlayer): Vec | null {
  if (Math.min(player.previous.y, player.position.y) - AIRFRAME_CONTACT_RADIUS > TERRAIN_MAX_HEIGHT + .003) {
    // Solid rocks can extend above the height field. K's body/wing spheres are
    // the common solid-obstacle collision shape.
    if (Math.min(player.previous.y, player.position.y) - AIRFRAME_CONTACT_RADIUS > TERRAIN_MAX_HEIGHT + 16) return null;
  } else {
    const a = normalizeQuaternion(player.previousQuaternion), b = normalizeQuaternion(player.quaternion);
    const cosine = Math.min(1, Math.abs(a.x * b.x + a.y * b.y + a.z * b.z + a.w * b.w));
    const angle = 2 * Math.acos(cosine), translation = Math.hypot(player.position.x - player.previous.x, player.position.z - player.previous.z);
    // The height field's slope is bounded by .3 and its Hessian by .02. This
    // deliberately loose bound covers all radial/7-fold terms, including r=0.
    const curvature = AIRFRAME_CONTACT_RADIUS * angle ** 2 * 1.3 + .02 * (translation + AIRFRAME_CONTACT_RADIUS * angle) ** 2;
    const evaluate = (t: number) => {
      const center = lerpVec(player.previous, player.position, t), q = interpolateQuaternion(a, b, t);
      let gap = Infinity, lowest = copyVec(center);
      for (let i = 0; i < AIRFRAME_CONTACT_VERTICES.length; i += 3) {
        const p = addVec(center, rotateVec({ x: AIRFRAME_CONTACT_VERTICES[i], y: AIRFRAME_CONTACT_VERTICES[i + 1], z: AIRFRAME_CONTACT_VERTICES[i + 2] }, q));
        const clearance = p.y - terrainHeight(p.x, p.z);
        if (clearance < gap) { gap = clearance; lowest = p; }
      }
      return { gap, point: lowest };
    };
    type Sample = ReturnType<typeof evaluate>;
    const search = (lo: number, first: Sample, hi: number, last: Sample, depth: number): Vec | null => {
      if (first.gap <= .003) return { ...first.point, y: terrainHeight(first.point.x, first.point.z) };
      if (Math.min(first.gap, last.gap) - curvature * (hi - lo) ** 2 / 8 > .003) return null;
      if (depth === 20) return copyVec(first.gap < last.gap ? first.point : last.point);
      const mid = (lo + hi) / 2, sample = evaluate(mid);
      return search(lo, first, mid, sample, depth + 1) ?? search(mid, sample, hi, last, depth + 1);
    };
    const hit = search(0, evaluate(0), 1, evaluate(1), 0); if (hit) return hit;
  }
  for (const sphere of AIRCRAFT_HIT_SPHERES) {
    const from = addVec(player.previous, rotateVec(sphere.center, player.previousQuaternion));
    const to = addVec(player.position, rotateVec(sphere.center, player.quaternion));
    const hit = sweepObstacles(from, to, sphere.radius);
    if (hit?.obstacleId !== null && hit) return hit.point;
  }
  return null;
}
